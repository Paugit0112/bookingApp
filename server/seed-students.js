function buildFullName(firstname, middlename, lastname) {
  const mid = middlename && middlename.trim() && middlename.trim() !== '-'
    ? ' ' + middlename.trim() : ''
  return `${firstname.trim()}${mid} ${lastname.trim()}`
}

async function seed() {
  const db = await mysql.createConnection({
    host: '127.0.0.1', port: 3307, user: 'root', password: '', database: 'evalbook',
  })

  let inserted = 0, skipped = 0

  for (const [student_id, lastname, firstname, middlename, program, section] of students) {
    const full_name = buildFullName(firstname, middlename, lastname)
    const sid = student_id.trim().toUpperCase()
    try {
      await db.execute(
        'INSERT IGNORE INTO students (id, full_name, student_id, section) VALUES (UUID(), ?, ?, ?)',
        [full_name, sid, section.trim()]
      )
      const [res] = await db.execute('SELECT ROW_COUNT() as n')
      if (res[0].n > 0) inserted++; else skipped++
    } catch (err) {
      console.error(`  ERROR ${sid}: ${err.message}`)
    }
  }

  console.log(`\nDone: ${inserted} inserted, ${skipped} skipped (duplicates)`)
  await db.end()
}

